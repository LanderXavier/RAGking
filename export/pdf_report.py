def _styles():
    base = getSampleStyleSheet()
    title_s = ParagraphStyle("CTitle", parent=base["Heading1"],
                             fontSize=22, textColor=colors.HexColor("#2c3e50"),
                             spaceAfter=6, alignment=TA_CENTER, fontName="Helvetica-Bold")
    head_s  = ParagraphStyle("CHead",  parent=base["Heading2"],
                             fontSize=13, textColor=colors.HexColor("#34495e"),
                             spaceAfter=10, spaceBefore=10, fontName="Helvetica-Bold")
    cell_s  = ParagraphStyle("CCell",  parent=base["Normal"],
                             fontName="Helvetica", fontSize=8.5, leading=10, alignment=TA_LEFT)
    hdr_s   = ParagraphStyle("CHdr",   parent=base["Normal"],
                             fontName="Helvetica-Bold", fontSize=9, leading=11,
                             textColor=colors.whitesmoke, alignment=TA_CENTER)
    score_s = ParagraphStyle("CScore", parent=base["Normal"],
                             fontName="Helvetica-Bold", fontSize=14, leading=16,
                             textColor=colors.whitesmoke, alignment=TA_CENTER)
    compact_s = ParagraphStyle("CCompact", parent=cell_s,
                               fontSize=7, leading=8, alignment=TA_CENTER)
    compact_h = ParagraphStyle("CCompactH", parent=hdr_s, fontSize=7.5, leading=9)
    return base, title_s, head_s, cell_s, hdr_s, score_s, compact_s, compact_h


def _P(text, style):
    return Paragraph(str(text), style)


def _safe_text(value, max_len=None):
    s = "" if value is None else str(value)
    s = s.replace("\r\n", "\n").replace("\r", "\n")
    if max_len and len(s) > max_len:
        s = s[: max_len - 1] + "…"
    s = xml_escape(s)
    return s.replace("\n", "<br/>")


