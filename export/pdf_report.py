# ══════════════════════════════════════════════════════════════════════════════
def generate_pdf_report(
    results_df: pd.DataFrame,
    output_path: str,
    operational_factors: dict = None,
    report_lang: str = "en",
    failure_count_override: int = None,
) -> bool:
    info("Generating PDF report...")
    time.sleep(0.2)

    # temporary files prefix for plots/images
    _TMP = "/tmp/ragking_"
    report_lang = (report_lang or "en").lower()
    if report_lang not in REPORT_TEXT:
        report_lang = "en"
    R  = REPORT_TEXT[report_lang]
    w  = state["weights"]
    c  = state["llm"]

    base, title_s, head_s, cell_s, hdr_s, score_s, compact_s, compact_h = _styles()

    def P(text, style=None):
        return _P(text, style or cell_s)

    doc   = SimpleDocTemplate(output_path, pagesize=letter,
                              topMargin=0.5*inch, bottomMargin=0.5*inch)
    story = []

    # ── Cover ────────────────────────────────────────────────────────────────
    story += [
        Spacer(1, 0.4*inch),
        _P(R["title"],    title_s),
        _P(R["subtitle"], base["Normal"]),
        Spacer(1, 0.3*inch),
        _P(f"<i>{R['generated']}: {datetime.now().strftime('%B %d, %Y · %H:%M')}</i>", base["Normal"]),
        Spacer(1, 0.5*inch),
    ]

    # ── Overall Score ─────────────────────────────────────────────────────────
    overall_score = results_df["RAGking_score"].mean()
    overall_label = get_score_label(overall_score)
    label_map = {
        "Excellent": R["excellent"], "Good": R["good"],
        "Acceptable": R["acceptable"], "Needs Improvement": R["needs_improvement"],
    }
    overall_label_text = label_map.get(overall_label, overall_label)
    interp_key = LABEL_TO_INTERP_KEY.get(overall_label, "interp_acceptable")

    story.append(_P(R["overall"], head_s))
    sc_tbl = Table(
        [[_P(f"{overall_score:.2f}/100", score_s), _P(overall_label_text, score_s)]],
        colWidths=[3.4*inch, 3.4*inch],
    )
    sc_tbl.setStyle(TableStyle([
        ("BACKGROUND",    (0, 0), (-1, -1), rl_score_color(overall_score)),
        ("ALIGN",         (0, 0), (-1, -1), "CENTER"),
        ("TOPPADDING",    (0, 0), (-1, -1), 12),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 12),
        ("BOX",           (0, 0), (-1, -1), 2, _DARK),
    ]))
    story += [sc_tbl, Spacer(1, 0.2*inch),
              _P(f"<b>{R['interpretation']}:</b> {R[interp_key]}", base["Normal"]),
              Spacer(1, 0.3*inch)]

    # ── Key Metrics ───────────────────────────────────────────────────────────
    if failure_count_override is not None:
        fail_rate = min(max(float(failure_count_override) / max(len(results_df), 1), 0.0), 1.0)
    else:
        fail_rate = float(results_df["is_failure"].sum()) / max(len(results_df), 1)

    story.append(_P(R["metrics"], head_s))
    story.append(_P("FORMULAS USED", ParagraphStyle("FHead", parent=base["Normal"], fontName="Helvetica-Bold", fontSize=10, spaceBefore=6)))
    formula_art = _formula_image_flowable()
    if formula_art is not None:
        story.append(formula_art)
        story.append(Spacer(1, 0.15*inch))
    else:
        fstyle = ParagraphStyle("Formula", parent=base["Normal"], fontName="Courier", fontSize=9, leading=12)
        story.append(Preformatted("RAGking = (wC · C_norm + wE · E_norm + wL · L_norm + wM · M_norm + wF · F_norm) × 100", fstyle))
        story.append(Spacer(1, 0.06*inch))
        story.append(Preformatted("Cost per query = (PromptTokens / 1e6) · Input$/1M + (CompletionTokens / 1e6) · Output$/1M", fstyle))
        story.append(Spacer(1, 0.06*inch))
        story.append(Preformatted("Economic Efficiency = Correctness / Cost_per_query  (Correctness per USD)", fstyle))
        story.append(Spacer(1, 0.06*inch))
        story.append(Preformatted("Token Efficiency = (PromptTokens + CompletionTokens) / max(Correctness, 1)", fstyle))
        story.append(Spacer(1, 0.12*inch))

    metrics_rows = [
        [P(R["metric"], hdr_s), P(R["value"], hdr_s), P(R["observation"], hdr_s)],
        [P(R["samples"]),          P(str(len(results_df))),                        P("Total evaluated queries")],
        [P(R["correctness_avg"]),  P(f"{results_df['Correctness'].mean():.2f}/5"), P("LLM-as-a-Judge score")],
        [P(R["latency_avg"]),      P(f"{results_df['Execution Time (ms)'].mean():.1f} ms"), P("Average response time")],
        [P("Avg cost per query (USD)"), P(f"${results_df['cost_per_query'].mean():.6f}"), P("Average API cost per single query")],
        [P("Economic Efficiency (Correctness/USD)"), P(f"{results_df['economic_eff_raw'].mean():.4f}"), P("Correctness per USD (mean)")],
        [P("Token Efficiency (tok/pt)"), P(f"{results_df['token_eff_raw'].mean():.2f}"), P("(Prompt + Completion) / max(Correctness, 1), lower is better")],
        [P(R["prompt_tokens_avg"]),P(f"{results_df['Prompt Tokens'].mean():.0f}"),          P("Average prompt tokens")],
        [P(R["completion_tokens_avg"]), P(f"{results_df['Completion Tokens'].mean():.0f}"), P("Average completion tokens")],
        [P(R["total_tokens_avg"]), P(f"{results_df['Total Tokens'].mean():.0f}"),           P("Average total tokens")],
        [P(R["sim_avg"]),          P(f"{results_df['String Similarity'].mean():.3f}"),      P("Mean similarity vs expected")],
        [P(R["fail_rate"]),        P(f"{fail_rate * 100:.1f}%"),                            P("Empty/invalid response ratio")],
        [P(R["std"]),              P(f"{results_df['RAGking_score'].std():.2f}"),            P("Performance variability")],
    ]
    mt = Table(metrics_rows, colWidths=[2.2*inch, 1.3*inch, 3.8*inch], repeatRows=1)
    mt.setStyle(_BASE_TABLE_STYLE)
    story += [mt, Spacer(1, 0.12*inch)]

    # If there is a global operational factor, surface it early in the report
    if operational_factors and "__global__" in operational_factors:
        g = operational_factors["__global__"]
        try:
            g_desc = f"Global — Deploy: {g['deploy_hours']}h | Difficulty: {g['difficulty']}/5 | Maint: {g['maintenance_hours_week']}h/wk"
        except Exception:
            # Fallback: stringify the entry
            g_desc = str(g)
        story.append(_P("<b>Global operational factors:</b>", base["Normal"]))
        story.append(_P(g_desc, base["Normal"]))
        story.append(Spacer(1, 0.2*inch))

    # ── Per-question compact table ────────────────────────────────────────────
    story.append(_P(R["per_q"], head_s))
    story.append(_P(f"<i>{R['tok_eff_note']}</i>", base["Normal"]))
    story.append(Spacer(1, 0.1*inch))

    metric_cols = [
        "Prompt Tokens", "Completion Tokens", "Total Tokens",
        "Execution Time (ms)", "Correctness", "String Similarity",
        "cost_per_query", "economic_eff_raw", "token_eff_raw",
    ]
    short = {"Prompt Tokens":"P","Completion Tokens":"Comp","Total Tokens":"Tok",
             "Execution Time (ms)":"Time","Correctness":"Corr",
             "String Similarity":"Sim","cost_per_query":"Cost","economic_eff_raw":"Econ","token_eff_raw":"TokEff"}

    def fmt(col, v):
        if v is None: return ""
        try:
            if pd.isna(v): return ""
        except Exception: pass
        if isinstance(v, (bool, np.bool_)): return "1" if bool(v) else "0"
        if col in {"Prompt Tokens","Completion Tokens","Total Tokens"}:
            return str(int(float(v)))
        if col == "Execution Time (ms)": return f"{float(v):.0f}"
        if col == "Correctness":
            fv = float(v); return f"{fv:.0f}" if abs(fv - round(fv)) < 1e-6 else f"{fv:.1f}"
        if col == "String Similarity": return f"{float(v):.3f}"
        if col == "cost_per_query": return f"${float(v):.6f}"
        if col == "economic_eff_raw": return f"{float(v):.4f}"
        if col == "token_eff_raw": return f"{float(v):.2f}"
        try:
            fv = float(v); return f"{fv:.3f}" if abs(fv) < 1 else f"{fv:.2f}"
        except Exception: return str(v)

    hdr = [_P("Q", compact_h)] + [_P(short.get(metric_name, metric_name), compact_h) for metric_name in metric_cols]
    pq_rows = [hdr]
    for i, row in results_df.reset_index(drop=True).iterrows():
        cells = [_P(f"q{i+1}", compact_s)]
        for metric_name in metric_cols:
            cells.append(_P(_safe_text(fmt(metric_name, row.get(metric_name, "")), max_len=32), compact_s))
        pq_rows.append(cells)

    q_w = 0.45*inch
    col_w = (7.5*inch - q_w) / len(metric_cols)
    pq_tbl = Table(pq_rows, colWidths=[q_w] + [col_w]*len(metric_cols), repeatRows=1)
    pq_tbl.setStyle(TableStyle([
        ("BACKGROUND",    (0, 0), (-1,  0), _DARK),
        ("GRID",          (0, 0), (-1, -1), 0.5, colors.grey),
        ("ALIGN",         (0, 0), (-1, -1), "CENTER"),
        ("VALIGN",        (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING",   (0, 0), (-1, -1), 2),
        ("RIGHTPADDING",  (0, 0), (-1, -1), 2),
        ("TOPPADDING",    (0, 0), (-1, -1), 2),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
        ("ROWBACKGROUNDS",(0, 1), (-1, -1), [colors.white, _LIGHT]),
    ]))
    story += [pq_tbl, PageBreak()]

    # ── Dashboard ─────────────────────────────────────────────────────────────
    story.append(_P("DETAILED METRICS ANALYSIS", head_s))
    dash_path = _TMP + "dashboard.png"
    plot_dashboard(results_df, dash_path)
    try:
        story.append(Image(dash_path, width=7.5*inch, height=5.5*inch))
    except Exception as e:
        story.append(_P(f"<i>Error loading dashboard: {e}</i>", base["Normal"]))
    story.append(PageBreak())

    # ── Individual distributions ──────────────────────────────────────────────
    story.append(_P("INDIVIDUAL DISTRIBUTIONS", head_s))
    for col, label, color in [
        ("Correctness",        "Correctness Score [1–5]", "#2ecc71"),
        ("Execution Time (ms)","Latency (ms)",            "#f39c12"),
    ]:
        p = _TMP + f"dist_{col.replace(' ','_')}.png"
        plot_distribution(results_df[col], p, xlabel=label, color=color)
        try:
            story.append(Image(p, width=6.5*inch, height=3.5*inch))
            story.append(Spacer(1, 0.2*inch))
        except Exception: pass
    story.append(PageBreak())

    # ── Model comparison (if applicable) ─────────────────────────────────────
    if "Model" in results_df.columns and len(results_df["Model"].unique()) > 1:
        story.append(_P("MODEL COMPARISON", head_s))
        cmp_path = _TMP + "model_cmp.png"
        plot_model_comparison(results_df, cmp_path)
        try:
            story.append(Image(cmp_path, width=7*inch, height=4*inch))
        except Exception: pass
        story.append(PageBreak())

    # ── Config & Weights ─────────────────────────────────────────────────────
    story.append(_P(R["system_config"], head_s))
    cfg_rows = [
        [P(R["parameter"], hdr_s), P(R["value"], hdr_s)],
        [P("LLM Model (Response)"), P(c["response_model"])],
        [P("LLM Model (Judge)"),    P(c.get("judge_model", ""))],
        [P("Embedding Model"),      P(c["embedding_model"])],
        [P("Response cost (per 1K tokens)"), P(f"${c.get('response_cost_per_1k', 0.0):.6f}")],
        [P("Input cost (per 1M tokens)"),   P(f"${c.get('input_cost_per_1m', 0.0):.6f}")],
        [P("Output cost (per 1M tokens)"),  P(f"${c.get('output_cost_per_1m', 0.0):.6f}")],
        [P("Weight Correctness (wC)"),     P(f"{w['correctness']:.2f}")],
        [P("Weight Economic Eff. (wE)"),P(f"{w.get('economic', w.get('token_eff', 0.0)):.2f}")],
        [P("Weight Latency (wL)"),         P(f"{w['latency']:.2f}")],
        [P("Weight Maintenance (wM)"),     P(f"{w['maintenance']:.2f}")],
        [P("Weight Failure Rate (wF)"),    P(f"{w['failure']:.2f}")],
    ]
    if operational_factors:
        cfg_rows.append([P("Operational Factors"), P("")])
        for k, v in operational_factors.items():
            lbl = k if k != "__global__" else "Global"
            desc = f"Deploy: {v['deploy_hours']}h | Difficulty: {v['difficulty']}/5 | Maint: {v['maintenance_hours_week']}h/wk"
            cfg_rows.append([P(lbl), P(desc)])

    cfg_tbl = Table(cfg_rows, colWidths=[2.8*inch, 4.0*inch], repeatRows=1)
    cfg_tbl.setStyle(_BASE_TABLE_STYLE)
    # Note: RAGking formula is shown earlier under 'FORMULAS USED' — avoid duplicate here
    story += [cfg_tbl, Spacer(1, 0.3*inch), PageBreak()]

    # ── Recommendations ───────────────────────────────────────────────────────
    story.append(_P(R["analysis"], head_s))
    c_mean = results_df["Correctness"].mean()
    l_mean = results_df["Execution Time (ms)"].mean()
    s_mean = results_df["String Similarity"].mean()
    f_pct  = fail_rate * 100

    story.append(_P(f"<b>{R['strengths']}:</b>", base["Normal"]))
    strengths = []
    if c_mean >= 4.0:   strengths.append(f"• Excellent answer quality: {c_mean:.2f}/5")
    if l_mean < 1000:   strengths.append(f"• Good response time: {l_mean:.0f} ms")
    if s_mean >= 0.75:  strengths.append(f"• High semantic similarity: {s_mean:.3f}")
    if f_pct < 5:       strengths.append(f"• Low failure rate: {f_pct:.1f}%")
    if not strengths:   strengths = ["• The system is operating at an acceptable level"]
    for s in strengths:
        story.append(_P(s, base["Normal"]))

    story.append(Spacer(1, 0.15*inch))
    story.append(_P(f"<b>{R['improvements']}:</b>", base["Normal"]))
    improvements = []
    if c_mean < 3.5:    improvements.append(f"• Improve answer quality: {c_mean:.2f}/5")
    if l_mean > 2000:   improvements.append(f"• Optimize latency: {l_mean:.0f} ms")
    if s_mean < 0.6:    improvements.append(f"• Improve semantic relevance: {s_mean:.3f}")
    if f_pct > 10:      improvements.append(f"• Reduce failure rate: {f_pct:.1f}%")
    if not improvements: improvements = ["• No critical improvement areas detected"]
    for imp in improvements:
        story.append(_P(imp, base["Normal"]))

    story += [
        Spacer(1, 0.3*inch),
        _P(f"<i>{R['report_footer']} · {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}</i>",
           base["Normal"]),
    ]

    try:
        doc.build(story)
        ok(f"PDF report  →  {output_path}")
        return True
    except Exception as e:
        err(f"PDF build error: {e}")
        return False


def _export_comparative_table(pdf_path: str, fw_names: list, comp_data: list):
    """Export the FULL COMPARATIVE ANALYSIS table to xlsx and csv formats."""
    import os
    from pathlib import Path
    
    # Derive output paths from PDF path
    pdf_dir = os.path.dirname(pdf_path)
    pdf_stem = Path(pdf_path).stem
    xlsx_path = os.path.join(pdf_dir, f"{pdf_stem}_FULL_COMPARATIVE_ANALYSIS.xlsx")
    csv_path = os.path.join(pdf_dir, f"{pdf_stem}_FULL_COMPARATIVE_ANALYSIS.csv")
    
    # Build DataFrame from comp_data
    rows_list = []
    for dimension, metric, values, diff_type in comp_data:
        row_dict = {
            "Dimension": dimension,
            "Metric": metric,
        }
        for i, fw_name in enumerate(fw_names):
            v = values[i] if i < len(values) else None
            if v is None:
                row_dict[fw_name] = ""
            elif isinstance(v, (int, float)):
                row_dict[fw_name] = round(v, 4) if isinstance(v, float) else v
            else:
                row_dict[fw_name] = str(v)
        rows_list.append(row_dict)
    
    df = pd.DataFrame(rows_list)
    
    # Export to xlsx
    try:
        df.to_excel(xlsx_path, sheet_name="Comparative Analysis", index=False)
        ok(f"Comparative table exported  →  {xlsx_path}")
    except Exception as e:
        err(f"XLSX export failed: {e}")
    
    # Export to csv
    try:
        df.to_csv(csv_path, index=False)
        ok(f"Comparative table exported  →  {csv_path}")
    except Exception as e:
        err(f"CSV export failed: {e}")


