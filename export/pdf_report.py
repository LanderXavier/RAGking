    # Calculate percentage variation taking V1 as the highest value.
    def calc_diff(values):
        nums = []
        for value in values:
            if value is None:
                continue
            try:
                nums.append(float(value))
            except Exception:
                continue

        if len(nums) < 2:
            return "—"

        v1 = max(nums)
        if v1 == 0:
            return "—"

        # For 2 frameworks this is the other value; for N frameworks this uses the minimum.
        v2 = min(nums)
        pct_change = ((v2 - v1) / v1) * 100
        return f"{pct_change:.2f}%"

